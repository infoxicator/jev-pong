import { BENCHMARK_PACE, DECISION_DEADLINE_MS, TACTIC_LABELS, type ReplayClip, type ReplayFile } from '../benchmark';
import { createGame, type GameState } from '../physics';
import { interpolateGame } from './interpolation';
import type { createArena3D } from './scene';
import type { CameraView } from './cameras';

function isFrame(frame: GameState) {
  return frame && Number.isFinite(frame.tick) && Number.isFinite(frame.tt?.height)
    && Boolean(frame.tt?.strokes) && Boolean(frame.tt?.velocity)
    && [frame.ball?.x, frame.ball?.y, frame.ball?.vx, frame.ball?.vy,
      frame.paddles?.left, frame.paddles?.right, frame.score?.left, frame.score?.right].every(Number.isFinite);
}
function parseReplay(text: string): ReplayFile {
  const replay = JSON.parse(text) as ReplayFile | null;
  if (!replay || replay.format !== 'jev-benchmark-replay-v1' || replay.pace !== BENCHMARK_PACE
    || !Array.isArray(replay.clips) || !replay.clips.length || replay.clips.length > 120
    || !replay.clips.every(clip => clip && (clip.side === 'left' || clip.side === 'right')
      && typeof clip.player === 'string' && typeof clip.scenario === 'string'
      && Object.hasOwn(TACTIC_LABELS, clip.shot)
      && [clip.applyTick, clip.contactTick, clip.landingTick].every(Number.isFinite)
      && clip.result && typeof clip.result.reason === 'string'
      && (!clip.result.landing || [clip.result.landing.x, clip.result.landing.y].every(Number.isFinite))
      && Array.isArray(clip.frames) && clip.frames.length >= 2 && clip.frames.length <= 500
      && clip.frames.every((frame, index) => isFrame(frame) && (index === 0 || frame.tick > clip.frames[index - 1].tick)))) {
    throw new Error('Select a replay JSON generated by npm run benchmark.');
  }
  return replay;
}

export function startBenchmarkReplay(
  arena: Awaited<ReturnType<typeof createArena3D>>, getView: () => CameraView,
) {
  document.body.dataset.role = 'benchmark';
  const $ = (id: string) => document.getElementById(id)!;
  const controls = $('benchmark-controls');
  const input = $('benchmark-file') as HTMLInputElement;
  const select = $('benchmark-clip') as HTMLSelectElement;
  const replayButton = $('benchmark-play') as HTMLButtonElement;
  const status = $('benchmark-status');
  controls.hidden = false;
  document.querySelector<HTMLElement>('.rally-stat')!.hidden = true;
  $('classic').textContent = 'Live exhibition ↗';
  $('classic').setAttribute('href', '/arena3d.html?spectate');
  $('replay').hidden = true;
  $('reset').hidden = true;
  $('brain-mode').textContent = 'RECORDED RALLIES';
  $('network').hidden = true;
  $('latency').textContent = `${DECISION_DEADLINE_MS} MS SHARED DEADLINE`;
  $('pace').textContent = `${BENCHMARK_PACE}× SHARED PACE`;
  $('seat').textContent = 'MATCHED SHOTS';
  $('phase-kicker').textContent = 'BENCHMARK REPLAY';
  $('phase-title').textContent = 'Load a rally';
  $('phase-detail').textContent = 'Choose the replay JSON generated by the benchmark.';
  $('lobby-actions').hidden = true;

  const idle = createGame('table-tennis');
  let file: ReplayFile | undefined, clip: ReplayClip | undefined;
  let start = 0, frameIndex = 0, animation = 0, stage = '';
  function play() {
    clip = file?.clips[Number(select.value)];
    if (!clip) return;
    start = performance.now();
    frameIndex = 0;
    stage = '';
    $('phase-overlay').hidden = true;
  }
  input.onchange = async () => {
    const selected = input.files?.[0];
    if (!selected) return;
    try {
      if (selected.size > 20_000_000) throw new Error('Replay file exceeds 20 MB.');
      file = parseReplay(await selected.text());
      select.replaceChildren(...file.clips.map((item, index) =>
        new Option(`${item.scenario} · ${item.player} · ${item.side}`, String(index))));
      select.disabled = replayButton.disabled = false;
      play();
    } catch (error) {
      status.textContent = error instanceof SyntaxError ? 'Select a valid benchmark replay JSON.' : (error as Error).message;
    }
  };
  select.onchange = replayButton.onclick = play;
  function frame(now: number) {
    if (clip && file) {
      const startTick = clip.frames[0].tick, endTick = clip.frames.at(-1)!.tick;
      const tick = Math.min(endTick, startTick + Math.max(0, now - start) * .12 * file.pace);
      while (clip.frames[frameIndex + 1]?.tick <= tick) frameIndex++;
      const before = clip.frames[frameIndex], after = clip.frames[frameIndex + 1];
      const rendered = after ? interpolateGame(before, after, (tick - before.tick) / (after.tick - before.tick)) : before;
      const landed = clip.landingTick >= 0 && tick >= clip.landingTick;
      arena.markLanding(landed ? clip.result.landing : null, clip.side);
      arena.render(rendered, getView(), now);
      $('tick').textContent = `TICK ${Math.floor(tick)}`;
      const nextStage = tick >= endTick ? 'finished' : landed ? 'landed' : tick >= clip.applyTick ? 'chosen' : 'deciding';
      if (nextStage !== stage) {
        stage = nextStage;
        const shot = TACTIC_LABELS[clip.shot];
        const placement = landed && clip.result.landing;
        const detail = placement ? ` · landed at x ${Math.round(placement.x)}, y ${Math.round(placement.y)}` : '';
        const outcome = stage === 'finished' ? ` · ${clip.result.reason.toLowerCase()}` : '';
        status.textContent = `${clip.player} · ${stage === 'deciding' ? 'choosing return' : shot + detail + outcome}`;
        document.body.dataset.benchmarkStage = stage;
      }
    } else {
      arena.render(idle, getView(), now);
    }
    animation = requestAnimationFrame(frame);
  }
  animation = requestAnimationFrame(frame);
  return () => cancelAnimationFrame(animation);
}
